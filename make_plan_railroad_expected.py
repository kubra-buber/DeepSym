def parse_problem_pddl(problem_path: str, objects_path: Optional[str] = None):
    return parse_problem_railroad(problem_path, objects_path)


def build_initial_state(
    objects: Sequence[str],
    obj_types: Dict[str, str],
    relations: Sequence[
        Tuple[str, str, str]
    ],
    counters: Dict[str, int],
):
    """Build native numeric DeepSym state."""

    fluents = set()

    for obj in objects:
        fluents.add(
            F("pickloc", obj)
        )

    for obj, typ in obj_types.items():
        fluents.add(
            F(typ, obj)
        )

    for rel, obj1, obj2 in relations:
        fluents.add(
            F(rel, obj1, obj2)
        )

    numeric_values = {
        "H": int(
            counters.get("H", 0)
        ),
        "S": int(
            counters.get("S", 0)
        ),
    }

    return (
        State(
            fluents=fluents,
            numeric_values=numeric_values,
        ),
        {
            "object": set(objects),
        },
    )


def state_key(
    state: State,
) -> Tuple[str, ...]:
    """Hashable key including fluent and numeric state."""

    parts = [
        f"F:{fluent}"
        for fluent in state.fluents
    ]

    parts.extend(
        f"N:{name}={value}"
        for name, value
        in state.numeric_values.items()
    )

    return tuple(
        sorted(parts)
    )


def action_base_name(
    action_name: str,
) -> str:
    return action_name.split()[0]


def is_stack_action(
    action_name: str,
) -> bool:
    return action_base_name(
        action_name
    ).startswith("stack")


def is_progress_state(
    state: State,
    previous_state: State,
) -> bool:
    """Whether H or S increased."""

    before = dict(
        previous_state.numeric_values
    )

    after = dict(
        state.numeric_values
    )

    return (
        after.get("H", 0)
        > before.get("H", 0)
        or
        after.get("S", 0)
        > before.get("S", 0)
    )


def progress_outcomes_for_plan(
    action_name: str,
    current_state: State,
    outcomes: Sequence[
        Tuple[State, float]
    ],
) -> List[Tuple[State, float]]:
    """Keep only progress branches for fixed stack plans."""

    if not is_stack_action(
        action_name
    ):
        return list(outcomes)

    return [
        (state, probability)
        for state, probability in outcomes
        if is_progress_state(
            state,
            current_state,
        )
    ]


def transition_safe(state: State, action) -> List[Tuple[State, float]]:
    """Call Railroad transition and normalize/merge identical states.

    `get_usable_actions` can be permissive with generated operators and negated
    fluents. Treat Railroad transition() as the final precondition check. If an
    action is rejected by transition(), skip it in the expected-reachability DP
    instead of crashing.
    """
    try:
        outcomes = transition(state, action)
    except Exception as exc:  # Railroad may raise bindings-side RuntimeError.
        msg = str(exc)
        if "Precondition not satisfied" in msg or "precondition" in msg.lower():
            return []
        raise

    merged: Dict[Tuple[str, ...], Tuple[State, float]] = {}

    for next_state, p in outcomes:
        p = float(p)
        if p <= 0.0:
            continue
        key = state_key(next_state)
        if key in merged:
            old_state, old_p = merged[key]
            merged[key] = (old_state, old_p + p)
        else:
            merged[key] = (next_state, p)

    total = sum(p for _, p in merged.values())
    if total <= 0.0:
        return []
    return [(s, p / total) for s, p in merged.values()]


def expected_reachability_plan(initial_state: State,
                               goal,
                               all_actions: Sequence,
                               max_steps: int,
                               debug: bool = False):
    """Compute finite-horizon expected reachability and a greedy policy."""
    state_store: Dict[Tuple[str, ...], State] = {state_key(initial_state): initial_state}
    policy: Dict[Tuple[Tuple[str, ...], int], Tuple[Optional[str], float]] = {}
    outcome_cache: Dict[Tuple[Tuple[str, ...], str], List[Tuple[State, float]]] = {}

    # Deterministic ordering for reproducibility. Prefer auxiliary actions when
    # they are immediately useful, then stack actions by name.
    sorted_actions = sorted(all_actions, key=lambda a: a.name)

    def heuristic_action_order(
        action,
    ) -> Tuple[int, str]:
        name = action.name

        if name.startswith("makebase"):
            return (0, name)

        if is_stack_action(name):
            return (1, name)

        return (2, name)

    @lru_cache(maxsize=None)
    def value(key: Tuple[str, ...], depth: int) -> float:
        state = state_store[key]

        if goal.evaluate(state):
            policy[(key, depth)] = (None, 1.0)
            return 1.0
        if depth <= 0:
            policy[(key, depth)] = (None, 0.0)
            return 0.0

        usable = get_usable_actions(state, sorted_actions)
        usable = sorted(usable, key=heuristic_action_order)
        if not usable:
            policy[(key, depth)] = (None, 0.0)
            return 0.0

        best_action_name: Optional[str] = None
        best_val = -1.0

        for action in usable:
            cache_key = (key, action.name)
            if cache_key not in outcome_cache:
                outcome_cache[cache_key] = transition_safe(state, action)
            outcomes = outcome_cache[cache_key]
            if not outcomes:
                continue

            expected = 0.0
            for next_state, p in outcomes:
                next_key = state_key(next_state)
                state_store.setdefault(next_key, next_state)
                expected += p * value(next_key, depth - 1)

            # Reproducible tie-break: higher expected value, then lower action name.
            if expected > best_val + 1e-12:
                best_val = expected
                best_action_name = action.name

        if best_val < 0.0:
            best_val = 0.0
            best_action_name = None

        policy[(key, depth)] = (best_action_name, best_val)
        return best_val

    start_key = state_key(initial_state)
    start_val = value(start_key, max_steps)

    return start_val, policy, state_store, outcome_cache, value


def choose_representative_outcome(
    current_state: State,
    outcomes: Sequence[
        Tuple[State, float]
    ],
    remaining_depth: int,
    value_fn,
    mode: str,
) -> Tuple[State, float]:
    """Choose one branch for representative plan output."""

    if not outcomes:
        raise ValueError(
            "Cannot choose from empty outcome list"
        )

    if mode == "probability":
        return max(
            outcomes,
            key=lambda item: item[1],
        )

    if mode == "value":
        return max(
            outcomes,
            key=lambda item: value_fn(
                state_key(item[0]),
                remaining_depth,
            ),
        )

    if mode == "progress":
        progress = [
            (state, probability)
            for state, probability in outcomes
            if is_progress_state(
                state,
                current_state,
            )
        ]

        if progress:
            return max(
                progress,
                key=lambda item: (
                    item[1],
                    value_fn(
                        state_key(item[0]),
                        remaining_depth,
                    ),
                ),
            )

        return max(
            outcomes,
            key=lambda item: item[1],
        )

    # Default: largest p * V contribution.
    return max(
        outcomes,
        key=lambda item: (
            item[1]
            * value_fn(
                state_key(item[0]),
                remaining_depth,
            )
        ),
    )


def rollout_policy(initial_state: State,
                   goal,
                   all_actions: Sequence,
                   max_steps: int,
                   policy,
                   outcome_cache,
                   value_fn,
                   outcome_mode: str):
    """Roll out the computed policy into one representative action sequence."""
    state = initial_state
    history: List[str] = []
    branch_probability = 1.0
    visited_guard = set()

    action_by_name = {a.name: a for a in all_actions}

    for remaining in range(max_steps, 0, -1):
        if goal.evaluate(state):
            break

        key = state_key(state)
        guard_key = (key, remaining)
        if guard_key in visited_guard:
            break
        visited_guard.add(guard_key)

        action_name, _ = policy.get((key, remaining), (None, 0.0))
        if action_name is None:
            break
        action = action_by_name[action_name]
        history.append(action.name)

        outcomes = outcome_cache.get((key, action.name))
        if outcomes is None:
            outcomes = transition_safe(state, action)
            outcome_cache[(key, action.name)] = outcomes
        if not outcomes:
            break

        state, chosen_p = choose_representative_outcome(
            state,
            outcomes,
            remaining - 1,
            value_fn,
            outcome_mode,
        )
        branch_probability *= float(chosen_p)

    return history, state, branch_probability


def max_probability_linear_plan(initial_state: State,
                                goal,
                                all_actions: Sequence,
                                max_steps: int):
    """Find the highest-probability single executable progress path to the goal.

    This is different from expected reachability. Expected reachability computes a
    policy that may take one action, observe a failure branch, and then use a
    fallback action. A plain DeepSym plan.txt cannot express that contingency.

    This function therefore ignores roll/tumble branches for stack actions and
    searches for a single successful branch sequence with maximum probability
    product. It is the right output mode before a closed-loop executor exists.
    """
    start_key = state_key(initial_state)
    state_store: Dict[Tuple[str, ...], State] = {start_key: initial_state}
    parent: Dict[Tuple[Tuple[str, ...], int], Tuple[Tuple[str, ...], int, str, float]] = {}
    best_cost: Dict[Tuple[Tuple[str, ...], int], float] = {(start_key, 0): 0.0}

    sorted_actions = sorted(all_actions, key=lambda a: a.name)
    queue: List[Tuple[float, int, int, Tuple[str, ...]]] = []
    push_counter = 0
    heapq.heappush(queue, (0.0, 0, push_counter, start_key))

    best_goal_node = None

    while queue:
        cost, depth, _seq, key = heapq.heappop(queue)
        node = (key, depth)
        if cost > best_cost.get(node, float("inf")) + 1e-12:
            continue

        state = state_store[key]
        if goal.evaluate(state):
            best_goal_node = node
            break
        if depth >= max_steps:
            continue

        for action in sorted(get_usable_actions(state, sorted_actions), key=lambda a: a.name):
            outcomes = transition_safe(state, action)
            if not outcomes:
                continue

            # A fixed linear plan can only represent success/progress branches.
            # Failure branches become plan failure, not a later fallback action.
            usable_outcomes = progress_outcomes_for_plan(action.name, state, outcomes)
            if not usable_outcomes:
                continue

            for next_state, p in usable_outcomes:
                p = float(p)
                if p <= 0.0:
                    continue
                next_key = state_key(next_state)
                state_store.setdefault(next_key, next_state)
                next_node = (next_key, depth + 1)
                next_cost = cost - math.log(max(p, 1e-12))
                if next_cost + 1e-12 < best_cost.get(next_node, float("inf")):
                    best_cost[next_node] = next_cost
                    parent[next_node] = (key, depth, action.name, p)
                    push_counter += 1
                    heapq.heappush(queue, (next_cost, depth + 1, push_counter, next_key))

    if best_goal_node is None:
        return 0.0, [], initial_state

    # Reconstruct path.
    actions: List[str] = []
    prob = 1.0
    node = best_goal_node
    final_state = state_store[node[0]]
    while node in parent:
        prev_key, prev_depth, action_name, p = parent[node]
        actions.append(action_name)
        prob *= float(p)
        node = (prev_key, prev_depth)
    actions.reverse()
    return prob, actions, final_state


