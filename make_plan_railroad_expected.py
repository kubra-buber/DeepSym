"""Railroad expected-reachability planner for DeepSym.

This version keeps the learned probabilistic effect branches instead of turning
all actions into nominal deterministic success branches. It computes a finite-
horizon expected reachability value:

    V(s, h) = 1                                      if goal(s)
            = 0                                      if h == 0
            = max_a sum_{s'} P(s' | s, a) V(s', h-1) otherwise

Important execution note
------------------------
This is a policy/value planner. DeepSym's current execute_plan.py still expects
one fixed plan.txt. Therefore this script writes a representative rollout of the
policy by following the outcome branch that contributes most to expected value.
That plan.txt is useful for debugging and for approximate open-loop execution,
but the full benefit of expected-reachability planning requires a closed-loop
executor:

    observe -> build symbolic state -> choose one action -> execute -> observe -> replan

Usage:
    python make_plan_railroad.py -opts opts.yaml -goal "(H3)" --debug-actions
"""

import argparse
import json
import math
import os
import re
import sys
from functools import lru_cache
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

import yaml

from railroad._bindings import AndGoal, Fluent as F, LiteralGoal, State
from railroad.core import Effect, Operator, transition
from railroad.planner import get_usable_actions


# Full learned effect distribution by original stack operator name.
OPERATOR_EFFECT_DISTS: Dict[str, Dict[str, float]] = {}


# ---------------------------------------------------------------------------
# Probability helpers
# ---------------------------------------------------------------------------

def _normalize_effect_distribution(prob_effects: Sequence[Dict], *, op_name: str) -> List[Dict]:
    """Merge duplicate effects and normalize probabilities.

    A true probabilistic transition needs a valid distribution. Learned JSON
    generated by learn_rules_railroad.py should already sum to 1; this function
    also protects against manual edits during debugging.
    """
    merged: Dict[str, float] = {}
    for pe in prob_effects:
        name = str(pe["effect_name"])
        p = float(pe["probability"])
        if p <= 0.0:
            continue
        merged[name] = merged.get(name, 0.0) + p

    total = sum(merged.values())
    if total <= 0.0:
        raise ValueError(f"Operator {op_name} has an empty effect distribution")

    if abs(total - 1.0) > 1e-6:
        print(
            f"WARNING: probabilities for {op_name} sum to {total:.6f}; normalizing.",
            file=sys.stderr,
        )

    return [
        {"probability": p / total, "effect_name": name}
        for name, p in sorted(merged.items())
    ]


