def parse_pddl_goal(goal_str: str):
    """Parse a small PDDL-style goal string into a Railroad goal expression."""
    negative_tokens = set(re.findall(r"\(not\s*\((\w+)\)\)", goal_str))

    without_not_clauses = re.sub(r"\(not\s*\(\w+\)\)", " ", goal_str)
    positive_tokens = [
        tok for tok in re.findall(r"\((\w+)\)", without_not_clauses)
        if tok.lower() not in {"and", "goal"}
    ]

    goals = [LiteralGoal(F(tok)) for tok in positive_tokens]
    goals.extend(LiteralGoal(~F(tok)) for tok in sorted(negative_tokens))

    # DeepSym's generated PDDL goals include these; add them for command-line
    # goal strings like "(H3)" or "(S4)".
    if "stacked" not in negative_tokens:
        goals.append(LiteralGoal(~F("stacked")))
    if "inserted" not in negative_tokens:
        goals.append(LiteralGoal(~F("inserted")))

    if not goals:
        raise ValueError(f"No goal fluents found in: {goal_str}")
    return goals[0] if len(goals) == 1 else AndGoal(goals)


def _extract_parenthesized_section(content: str, start_token: str, end_token: str) -> str:
    start = content.find(start_token)
    if start < 0:
        return ""
    start += len(start_token)
    end = content.find(end_token, start)
    if end < 0:
        end = len(content)
    return content[start:end]


def parse_objects_txt(objects_path: str) -> Dict[str, Dict[str, float]]:
    """Parse DeepSym objects.txt/plan header.

    Format:
        5
        O1 x y size
        ...
    """
    infos: Dict[str, Dict[str, float]] = {}
    if not os.path.exists(objects_path):
        return infos

    with open(objects_path, "r") as f:
        lines = [line.strip() for line in f if line.strip()]
    if not lines:
        return infos

    try:
        n = int(lines[0].split()[0])
    except Exception:
        return infos

    for line in lines[1:1 + n]:
        parts = line.split()
        if len(parts) < 4:
            continue
        infos[parts[0]] = {
            "x": float(parts[1]),
            "y": float(parts[2]),
            "size": float(parts[3]),
        }
    return infos


def parse_problem_pddl(problem_path: str, objects_path: Optional[str] = None):
    """Parse DeepSym problem.pddl for objects, types, relations, and counters."""
    with open(problem_path, "r") as f:
        content = f.read()

    object_infos = parse_objects_txt(objects_path) if objects_path else {}

    objects: List[str] = []
    if object_infos:
        objects = list(object_infos.keys())
    else:
        # Robustly parse only the :objects section, not the whole file.
        m = re.search(r":objects\s+(.*?)\s*\)\s*\(:init", content, re.DOTALL | re.IGNORECASE)
        if m:
            objects = re.findall(r"\bO\d+\b", m.group(1))

    init_block = _extract_parenthesized_section(content, ":init", "(:goal")

    obj_types: Dict[str, str] = {}
    for typ, obj in re.findall(r"\((objtype\d+)\s+(O\d+)\)", init_block):
        obj_types[obj] = typ

    relations: List[Tuple[str, str, str]] = []
    for rel, obj1, obj2 in re.findall(r"\((relation\d+)\s+(O\d+)\s+(O\d+)\)", init_block):
        relations.append((rel, obj1, obj2))

    counters = set(re.findall(r"\((H\d+|S\d+)\)", init_block))

    if not objects:
        # Fall back to any typed object names if the :objects section was absent.
        objects = sorted(obj_types.keys())

    missing_types = [obj for obj in objects if obj not in obj_types]
    if missing_types:
        raise ValueError(f"Objects missing objtype predicates in problem.pddl: {missing_types}")

    return objects, obj_types, relations, counters, object_infos


def build_initial_state(objects: Sequence[str],
                        obj_types: Dict[str, str],
                        relations: Sequence[Tuple[str, str, str]],
                        counters: Iterable[str]):
    fluents = set()

    for obj in objects:
        fluents.add(F("pickloc", obj))

    for obj, typ in obj_types.items():
        fluents.add(F(typ, obj))

    for rel, obj1, obj2 in relations:
        fluents.add(F(rel, obj1, obj2))

    counter_set = set(counters)
    fluents.add(F("H0" if not any(c.startswith("H") for c in counter_set) else next(c for c in counter_set if c.startswith("H"))))
    fluents.add(F("S0" if not any(c.startswith("S") for c in counter_set) else next(c for c in counter_set if c.startswith("S"))))

    return State(fluents=fluents), {"object": set(objects)}


# ---------------------------------------------------------------------------
# Expected reachability planner
# ---------------------------------------------------------------------------

def state_key(state: State) -> Tuple[str, ...]:
    """Hashable state key for DeepSym's zero-time symbolic states."""
    return tuple(sorted(str(f) for f in state.fluents))


def action_base_name(action_name: str) -> str:
    return action_name.split()[0]


def is_stack_action(action_name: str) -> bool:
    base = action_base_name(action_name)
    return base.startswith("stack")


def transition_safe(state: State, action) -> List[Tuple[State, float]]:
    """Call Railroad transition and normalize/merge identical states.

    get_usable_actions can be permissive with generated operators and negated
    fluents. transition() is the final precondition check. If transition rejects
    an action, skip it in the expected-reachability DP instead of crashing.
    """
    try:
        outcomes = transition(state, action)
    except Exception as exc:
        msg = str(exc)
        if "Precondition not satisfied" in msg or "precondition" in msg.lower():
            return []
        raise

    merged: Dict[Tuple[str, ...], Tuple[State, float]] = {}

    for next_state, p in outcomes:
        p = float(p)
        if p <= 0.0:
            continue
        key = state_key(next_state)
        if key in merged:
            old_state, old_p = merged[key]
            merged[key] = (old_state, old_p + p)
        else:
            merged[key] = (next_state, p)

    total = sum(p for _, p in merged.values())
    if total <= 0.0:
        return []

    return [(s, p / total) for s, p in merged.values()]

def expected_reachability_plan(initial_state: State,
                               goal,
                               all_actions: Sequence,
                               max_steps: int,
                               debug: bool = False):
    """Compute finite-horizon expected reachability and a greedy policy."""
    state_store: Dict[Tuple[str, ...], State] = {state_key(initial_state): initial_state}
    policy: Dict[Tuple[Tuple[str, ...], int], Tuple[Optional[str], float]] = {}
    outcome_cache: Dict[Tuple[Tuple[str, ...], str], List[Tuple[State, float]]] = {}

    # Deterministic ordering for reproducibility. Prefer auxiliary actions when
    # they are immediately useful, then stack actions by name.
    sorted_actions = sorted(all_actions, key=lambda a: a.name)

    def heuristic_action_order(action) -> Tuple[int, str]:
        name = action.name
        if name.startswith("increase_height") or name.startswith("increase_stack"):
            return (0, name)
        if name.startswith("makebase"):
            return (1, name)
        if is_stack_action(name):
            return (2, name)
        return (3, name)

    @lru_cache(maxsize=None)
    def value(key: Tuple[str, ...], depth: int) -> float:
        state = state_store[key]

        if goal.evaluate(state.fluents):
            policy[(key, depth)] = (None, 1.0)
            return 1.0
        if depth <= 0:
            policy[(key, depth)] = (None, 0.0)
            return 0.0

        usable = get_usable_actions(state, sorted_actions)
        usable = sorted(usable, key=heuristic_action_order)
        if not usable:
            policy[(key, depth)] = (None, 0.0)
            return 0.0

        best_action_name: Optional[str] = None
        best_val = -1.0

        for action in usable:
            cache_key = (key, action.name)
            if cache_key not in outcome_cache:
                outcome_cache[cache_key] = transition_safe(state, action)
            outcomes = outcome_cache[cache_key]
            if not outcomes:
                continue

            expected = 0.0
            for next_state, p in outcomes:
                next_key = state_key(next_state)
                state_store.setdefault(next_key, next_state)
                expected += p * value(next_key, depth - 1)

            # Reproducible tie-break: higher expected value, then lower action name.
            if expected > best_val + 1e-12:
                best_val = expected
                best_action_name = action.name

        if best_val < 0.0:
            best_val = 0.0
            best_action_name = None

        policy[(key, depth)] = (best_action_name, best_val)
        return best_val

    start_key = state_key(initial_state)
    start_val = value(start_key, max_steps)

    return start_val, policy, state_store, outcome_cache, value


def choose_representative_outcome(outcomes: Sequence[Tuple[State, float]],
                                  remaining_depth: int,
                                  value_fn,
                                  mode: str) -> Tuple[State, float]:
    """Choose one outcome branch for writing a representative plan.txt."""
    if not outcomes:
        raise ValueError("Cannot choose from empty outcome list")

    if mode == "probability":
        return max(outcomes, key=lambda item: item[1])

    if mode == "value":
        return max(outcomes, key=lambda item: value_fn(state_key(item[0]), remaining_depth))

    # Default: choose the branch with largest contribution p * V(s').
    return max(
        outcomes,
        key=lambda item: item[1] * value_fn(state_key(item[0]), remaining_depth),
    )


def rollout_policy(initial_state: State,
                   goal,
                   all_actions: Sequence,
                   max_steps: int,
                   policy,
                   outcome_cache,
                   value_fn,
                   outcome_mode: str):
    """Roll out the computed policy into one representative action sequence."""
    state = initial_state
    history: List[str] = []
    visited_guard = set()

    action_by_name = {a.name: a for a in all_actions}

    for remaining in range(max_steps, 0, -1):
        if goal.evaluate(state.fluents):
            break

        key = state_key(state)
        guard_key = (key, remaining)
        if guard_key in visited_guard:
            break
        visited_guard.add(guard_key)

        action_name, _ = policy.get((key, remaining), (None, 0.0))
        if action_name is None:
            break
        action = action_by_name[action_name]
        history.append(action.name)

        outcomes = outcome_cache.get((key, action.name))
        if outcomes is None:
            outcomes = transition_safe(state, action)
            outcome_cache[(key, action.name)] = outcomes
        if not outcomes:
            break

        state, _p = choose_representative_outcome(
            outcomes,
            remaining - 1,
            value_fn,
            outcome_mode,
        )

    return history, state


