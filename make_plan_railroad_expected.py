# Output and debugging
# ---------------------------------------------------------------------------

def extract_stack_actions(action_history: Sequence[str]) -> List[Tuple[str, str]]:
    """Extract physical stack commands as (below, above)."""
    result: List[Tuple[str, str]] = []
    for action_name in action_history:
        parts = action_name.split()
        if len(parts) == 3 and parts[0].startswith("stack"):
            result.append((parts[1], parts[2]))
    return result


def write_plan(plan_path: str,
               object_infos: Dict[str, Dict[str, float]],
               expected_probability: float,
               stack_actions: Sequence[Tuple[str, str]],
               goal_reached_in_rollout: bool) -> None:
    with open(plan_path, "w") as f:
        if object_infos:
            f.write(f"{len(object_infos)}\n")
            for name, info in object_infos.items():
                f.write(f"{name} {info['x']:.5f} {info['y']:.5f} {info['size']:.5f}\n")

        f.write(f"plan probability: {expected_probability:.6f}\n")
        if expected_probability > 0.0 and stack_actions:
            for below, above in stack_actions:
                f.write(f"stack {below.upper()} {above.upper()}\n")
        elif goal_reached_in_rollout:
            # No physical stack may be needed for a trivial goal.
            pass
        else:
            f.write("not found.\n")


def debug_action(action_name: str) -> None:
    parts = action_name.split()
    base = parts[0]
    dist = OPERATOR_EFFECT_DISTS.get(base)
    if dist is None:
        print("        auxiliary/deterministic")
        return
    dist_str = ", ".join(f"{k}:{v:.3f}" for k, v in sorted(dist.items()))
    print(f"        learned_dist=[{dist_str}]")


def main() -> None:
    parser = argparse.ArgumentParser("Railroad expected-reachability planner for DeepSym.")
    parser.add_argument("-opts", type=str, required=True, help="option file")
    parser.add_argument("-goal", type=str, default="(H3)", help="PDDL-style goal, e.g. '(H3)' or '(S4)'")
    parser.add_argument("-max-steps", type=int, default=25, help="finite-horizon planning depth in symbolic actions")
    parser.add_argument("--debug-actions", action="store_true", help="print chosen actions and learned distributions")
    parser.add_argument(
        "--rollout-outcome",
        choices=["contribution", "probability", "value"],
        default="contribution",
        help="how to choose representative outcome branches for writing plan.txt",
    )
    args = parser.parse_args()

    opts = yaml.safe_load(open(args.opts, "r"))
    save_dir = opts["save"]

    operators_path = os.path.join(save_dir, "railroad_operators.json")
    if not os.path.exists(operators_path):
        print(f"ERROR: Railroad operators not found at {operators_path}")
        print("Run learn_rules_railroad.py first.")
        sys.exit(1)

    all_operators = load_operators_from_json(operators_path)
    print(f"Loaded and reconstructed {len(all_operators)} probabilistic/auxiliary operators")

    problem_path = os.path.join(save_dir, "problem.pddl")
    objects_path = os.path.join(save_dir, "objects.txt")
    objects, obj_types, relations, counters, object_infos = parse_problem_pddl(problem_path, objects_path)

    print(f"Objects: {objects}")
    print(f"Types: {obj_types}")
    print(f"Relations: {len(relations)}")

    initial_state, objects_by_type = build_initial_state(objects, obj_types, relations, counters)
    print(f"Initial state built with {len(initial_state.fluents)} fluents")

    all_actions = []
    for op in all_operators:
        all_actions.extend(op.instantiate(objects_by_type))
    all_actions.sort(key=lambda a: a.name)
    print(f"Grounded {len(all_actions)} actions from {len(all_operators)} operators")

    goal = parse_pddl_goal(args.goal)
    print(f"Goal: {goal}")

    print("\n=== Starting Railroad expected-reachability planning ===")
    expected_p, policy, state_store, outcome_cache, value_fn = expected_reachability_plan(
        initial_state,
        goal,
        all_actions,
        args.max_steps,
        debug=args.debug_actions,
    )

    history, rollout_final_state = rollout_policy(
        initial_state,
        goal,
        all_actions,
        args.max_steps,
        policy,
        outcome_cache,
        value_fn,
        args.rollout_outcome,
    )
    rollout_goal = bool(goal.evaluate(rollout_final_state.fluents))

    print(f"Expected probability of reaching goal within {args.max_steps} symbolic actions: {expected_p:.6f}")
    print(f"Representative rollout reaches goal: {rollout_goal}")

    if history:
        for i, act in enumerate(history):
            print(f"Step {i}: {act}")
            if args.debug_actions:
                debug_action(act)
    else:
        print("No action selected by policy.")

    stack_actions = extract_stack_actions(history)

    plan_path = os.path.join(save_dir, "plan.txt")
    write_plan(plan_path, object_infos, expected_p, stack_actions, rollout_goal)

    print(f"\n=== Plan written to {plan_path} ===")
    print(f"Expected plan/policy probability: {expected_p:.6f}")
    print(f"Symbolic rollout actions: {len(history)}")
    print(f"Physical stack actions in representative rollout: {len(stack_actions)}")
    for below, above in stack_actions:
        print(f"  stack {above} on {below}")


if __name__ == "__main__":
    main()