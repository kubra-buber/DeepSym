def _effect_fluents(effect_name: str) -> set:
    """Map a DeepSym outcome to structural Railroad fluents.

    H/S progress is represented directly by numeric updates.
    """
    effect_name = str(effect_name)

    if effect_name in {"stacked", "inserted"}:
        return {
            F("instack", "?above"),
            F("stackloc", "?above"),
            ~F("stackloc", "?below"),
        }

    if effect_name in {
        "roll1",
        "roll2",
        "tumble1",
        "tumble2",
    }:
        return {F(effect_name)}

    return {F(effect_name)}


def _effect_numeric_updates(effect_name: str):
    """Map DeepSym progress outcomes to native H/S updates."""
    effect_name = str(effect_name)

    if effect_name == "stacked":
        return [
            NumericUpdate(
                "H",
                NumericUpdateOp.INCREASE,
                1,
            ),
            NumericUpdate(
                "S",
                NumericUpdateOp.INCREASE,
                1,
            ),
        ]

    if effect_name == "inserted":
        return [
            NumericUpdate(
                "S",
                NumericUpdateOp.INCREASE,
                1,
            ),
        ]

    return []


def build_probabilistic_stack_operator(
    spec: Dict,
) -> Operator:
    """Build one probabilistic learned stack operator."""

    below_type = spec.get(
        "below_type",
        spec.get("obj1_type"),
    )

    above_type = spec.get(
        "above_type",
        spec.get("obj2_type"),
    )

    if below_type is None or above_type is None:
        raise ValueError(
            f"Malformed stack operator spec: {spec}"
        )

    op_name = str(spec["name"])

    normalized_effects = (
        _normalize_effect_distribution(
            spec["prob_effects"],
            op_name=op_name,
        )
    )

    OPERATOR_EFFECT_DISTS[op_name] = {
        str(pe["effect_name"]): float(
            pe["probability"]
        )
        for pe in normalized_effects
    }

    preconditions = [
        F("pickloc", "?above"),
        F("stackloc", "?below"),
        F(below_type, "?below"),
        F(above_type, "?above"),
        F(
            spec["relation"],
            "?below",
            "?above",
        ),
    ]

    prob_branches = []

    for pe in normalized_effects:
        p = float(pe["probability"])
        effect_name = str(pe["effect_name"])

        branch_effect = Effect(
            time=0,
            resulting_fluents=_effect_fluents(
                effect_name
            ),
            numeric_updates=_effect_numeric_updates(
                effect_name
            ),
        )

        prob_branches.append(
            (
                p,
                [branch_effect],
            )
        )

    probabilistic_effect = Effect(
        time=0,
        resulting_fluents=set(),
        prob_effects=prob_branches,
    )

    # Preserve original DeepSym semantics: the placed object is consumed
    # regardless of which probabilistic outcome occurs.
    pickloc_removal = Effect(
        time=0,
        resulting_fluents={
            ~F("pickloc", "?above")
        },
    )

    return Operator(
        name=op_name,
        parameters=[
            ("?below", "object"),
            ("?above", "object"),
        ],
        preconditions=preconditions,
        effects=[
            probabilistic_effect,
            pickloc_removal,
        ],
    )


def build_auxiliary_operator(
    spec: Dict,
) -> Optional[Operator]:
    """Build the remaining non-learned operator.

    Legacy numbered bookkeeping specs are ignored.
    """

    operator_type = spec["type"]

    if operator_type in {
        "increase_height",
        "increase_stack",
    }:
        return None

    if operator_type == "makebase":
        return Operator(
            name="makebase",
            parameters=[
                ("?obj", "object")
            ],
            preconditions=[
                ~F("base")
            ],
            effects=[
                Effect(
                    time=0,
                    resulting_fluents={
                        F("base"),
                        ~F("pickloc", "?obj"),
                        F("stackloc", "?obj"),
                    },
                    numeric_updates=[
                        NumericUpdate(
                            "H",
                            NumericUpdateOp.INCREASE,
                            1,
                        ),
                        NumericUpdate(
                            "S",
                            NumericUpdateOp.INCREASE,
                            1,
                        ),
                    ],
                )
            ],
        )

    raise ValueError(
        f"Unknown auxiliary operator type: "
        f"{operator_type}"
    )


def load_operators_from_json(
    json_path: str,
) -> List[Operator]:
    """Reconstruct learned and auxiliary Railroad operators."""

    with open(json_path, "r") as f:
        all_specs = json.load(f)

    OPERATOR_EFFECT_DISTS.clear()

    operators: List[Operator] = []

    for spec in all_specs["stack_operators"]:
        operators.append(
            build_probabilistic_stack_operator(
                spec
            )
        )

    for spec in all_specs.get(
        "auxiliary_operators",
        [],
    ):
        operator = build_auxiliary_operator(
            spec
        )

        if operator is not None:
            operators.append(operator)

    return operators


def parse_deepsym_goal(goal_str: str):
    """Parse H/S tokens as exact numeric goals."""

    negative_tokens = set(
        re.findall(
            r"\(not\s*\((\w+)\)\)",
            goal_str,
        )
    )

    without_not_clauses = re.sub(
        r"\(not\s*\(\w+\)\)",
        " ",
        goal_str,
    )

    positive_tokens = [
        token
        for token in re.findall(
            r"\((\w+)\)",
            without_not_clauses,
        )
        if token.lower()
        not in {"and", "goal"}
    ]

    def token_goal(
        token: str,
        *,
        negated: bool = False,
    ):
        match = re.fullmatch(
            r"([HS])(\d+)",
            token,
            flags=re.IGNORECASE,
        )

        if match:
            variable = match.group(1).upper()
            value = int(match.group(2))

            op = (
                NumericCompareOp.NE
                if negated
                else NumericCompareOp.EQ
            )

            return NumericGoal(
                NumericCondition(
                    variable,
                    op,
                    value,
                )
            )

        return LiteralGoal(
            ~F(token)
            if negated
            else F(token)
        )

    goals = [
        token_goal(token)
        for token in positive_tokens
    ]

    goals.extend(
        token_goal(
            token,
            negated=True,
        )
        for token in sorted(
            negative_tokens
        )
    )

    if not goals:
        raise ValueError(
            f"No goal conditions found in: "
            f"{goal_str}"
        )

    if len(goals) == 1:
        return goals[0]

    return AndGoal(goals)


# Backward-compatible name used by older diagnostic scripts.
parse_pddl_goal = parse_deepsym_goal


def _extract_parenthesized_section(content: str, start_token: str, end_token: str) -> str:
    start = content.find(start_token)
    if start < 0:
        return ""
    start += len(start_token)
    end = content.find(end_token, start)
    if end < 0:
        end = len(content)
    return content[start:end]


def parse_objects_txt(objects_path: str) -> Dict[str, Dict[str, float]]:
    """Parse DeepSym objects.txt/plan header.

    Format:
        5
        O1 x y size
        ...
    """
    infos: Dict[str, Dict[str, float]] = {}
    if not os.path.exists(objects_path):
        return infos

    with open(objects_path, "r") as f:
        lines = [line.strip() for line in f if line.strip()]
    if not lines:
        return infos

    try:
        n = int(lines[0].split()[0])
    except Exception:
        return infos

    for line in lines[1:1 + n]:
        parts = line.split()
        if len(parts) < 4:
            continue
        infos[parts[0]] = {
            "x": float(parts[1]),
            "y": float(parts[2]),
            "size": float(parts[3]),
        }
    return infos


def parse_problem_railroad(scene_path: str, objects_path: Optional[str] = None):
    """Parse DeepSym/Railroad scene JSON for objects, types, relations, counters.

    This replaces the previous use of problem.pddl in the Railroad path.  The
    JSON is written by recognize.py as save_dir/railroad_problem.json.

    Expected format:
        {
          "objects": [
             {"name": "O1", "type": "objtype3", "loc": [x, y], "size": s}, ...
          ],
          "relations": [
             {"name": "relation0", "below": "O1", "above": "O2"}, ...
          ],
          "counters": {"H": "H0", "S": "S0"}
        }
    """
    if not os.path.exists(scene_path):
        raise FileNotFoundError(
            f"Missing {scene_path}. Run recognize.py first; it should write railroad_problem.json."
        )

    with open(scene_path, "r") as f:
        data = json.load(f)

    raw_objects = data.get("objects", [])
    if not raw_objects:
        raise ValueError(f"{scene_path} has no objects")

    objects: List[str] = []
    obj_types: Dict[str, str] = {}
    object_infos: Dict[str, Dict[str, float]] = {}

    for obj in raw_objects:
        name = str(obj["name"]).upper()
        typ = str(obj["type"])
        loc = obj.get("loc", obj.get("location", [0.0, 0.0]))
        size = float(obj.get("size", 0.1))
        objects.append(name)
        obj_types[name] = typ
        object_infos[name] = {"x": float(loc[0]), "y": float(loc[1]), "size": size}

    # objects.txt is still allowed only as execution geometry fallback.  It is
    # not a symbolic planning input and can be removed once plan writing uses
    # railroad_problem.json directly everywhere.
    if objects_path and os.path.exists(objects_path):
        txt_infos = parse_objects_txt(objects_path)
        if txt_infos:
            object_infos.update({k.upper(): v for k, v in txt_infos.items()})

    relations: List[Tuple[str, str, str]] = []
    for rel in data.get("relations", []):
        if isinstance(rel, dict):
            r = str(rel.get("name", rel.get("relation")))
            below = str(rel.get("below", rel.get("obj1"))).upper()
            above = str(rel.get("above", rel.get("obj2"))).upper()
        else:
            r, below, above = rel
            r = str(r)
            below = str(below).upper()
            above = str(above).upper()
        relations.append((r, below, above))

    def parse_counter_value(
        variable: str,
        raw,
    ) -> int:
        if raw is None:
            return 0

        if isinstance(raw, bool):
            raise ValueError(
                f"Invalid {variable} counter value: "
                f"{raw!r}"
            )

        if isinstance(raw, int):
            return int(raw)

        value = str(raw).strip().upper()

        match = re.fullmatch(
            rf"{variable}(\d+)",
            value,
        )

        if match:
            return int(match.group(1))

        if re.fullmatch(
            r"[+-]?\d+",
            value,
        ):
            return int(value)

        raise ValueError(
            f"Invalid {variable} counter value: "
            f"{raw!r}"
        )

    numeric_data = data.get(
        "numeric_state"
    )

    if isinstance(
        numeric_data,
        dict,
    ):
        counters = {
            "H": parse_counter_value(
                "H",
                numeric_data.get("H", 0),
            ),
            "S": parse_counter_value(
                "S",
                numeric_data.get("S", 0),
            ),
        }

    else:
        legacy_data = data.get(
            "counters",
            {},
        )

        if isinstance(
            legacy_data,
            dict,
        ):
            counters = {
                "H": parse_counter_value(
                    "H",
                    legacy_data.get("H", 0),
                ),
                "S": parse_counter_value(
                    "S",
                    legacy_data.get("S", 0),
                ),
            }

        else:
            tokens = [
                str(v).strip().upper()
                for v in legacy_data
            ]

            h_token = next(
                (
                    v
                    for v in tokens
                    if re.fullmatch(
                        r"H\d+",
                        v,
                    )
                ),
                "H0",
            )

            s_token = next(
                (
                    v
                    for v in tokens
                    if re.fullmatch(
                        r"S\d+",
                        v,
                    )
                ),
                "S0",
            )

            counters = {
                "H": parse_counter_value(
                    "H",
                    h_token,
                ),
                "S": parse_counter_value(
                    "S",
                    s_token,
                ),
            }

    missing_types = [obj for obj in objects if obj not in obj_types]
    if missing_types:
        raise ValueError(f"Objects missing types in railroad_problem.json: {missing_types}")

    return objects, obj_types, relations, counters, object_infos


